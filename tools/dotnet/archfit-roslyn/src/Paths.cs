using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace ArchfitRoslyn;

internal static class Paths
{
    public static string Full(string path) => Path.TrimEndingDirectorySeparator(Path.GetFullPath(path));

    public static bool IsUnder(string dir, string path) =>
        path.StartsWith(dir + Path.DirectorySeparatorChar, StringComparison.Ordinal);

    public static string Relative(string root, string path) =>
        Path.GetRelativePath(root, path).Replace(Path.DirectorySeparatorChar, '/');
}

// File classification per D8, on root-relative '/' paths.
internal static class Generated
{
    public static bool IsBuildOutputPath(string rel) =>
        rel.Split('/').SkipLast(1).Any(segment => segment is "obj" or "bin");

    public static bool IsGeneratedPath(string rel) =>
        IsBuildOutputPath(rel)
        || rel.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
        || rel.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase)
        || rel.EndsWith(".Designer.cs", StringComparison.OrdinalIgnoreCase);

    public static bool IsGenerated(string rel, SyntaxTree tree, CancellationToken ct) =>
        IsGeneratedPath(rel) || HasAutoGeneratedHeader(tree, ct);

    private static bool HasAutoGeneratedHeader(SyntaxTree tree, CancellationToken ct) =>
        tree.GetRoot(ct).GetLeadingTrivia().Any(t =>
            (t.IsKind(SyntaxKind.SingleLineCommentTrivia) || t.IsKind(SyntaxKind.MultiLineCommentTrivia))
            && t.ToString().Contains("<auto-generated", StringComparison.Ordinal));
}
