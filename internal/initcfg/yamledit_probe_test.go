// TestProbe_TopLevelKeys_Navigation verifies that top-level YAML keys
// (layers, modules, tools, rules) are accessible as MappingValueNode children
// of the document body MappingNode.
func TestProbe_TopLevelKeys_Navigation(t *testing.T) {
	f, err := parser.ParseBytes([]byte(sampleArchfitYAML), parser.ParseComments)
	if err != nil {
		t.Fatalf("ParseBytes: %v", err)
	}

	body, ok := f.Docs[0].Body.(*ast.MappingNode)
	if !ok {
		t.Fatalf("body is %T, want *ast.MappingNode", f.Docs[0].Body)
	}

	found := make(map[string]bool)
	for _, mv := range body.Values {
		key := mv.Key.(*ast.StringNode).Value
		found[key] = true
	}

	for _, want := range []string{probeKeyVersion, probeKeyLayers, probeKeyModules, probeKeyLanguages, probeKeyRules} {
		if !found[want] {
			t.Errorf("top-level key %q not found; found keys: %v", want, keysOf(found))
		}
	}
	t.Logf("CONFIRMED: top-level keys accessible via body.Values: %v", keysOf(found))
}

// TestProbe_Layers_SequenceValues reads the layers: sequence and extracts
// string values, confirming the AST path for reading the allowed-layers set.
func TestProbe_Layers_SequenceValues(t *testing.T) {
	f, err := parser.ParseBytes([]byte(sampleArchfitYAML), parser.ParseComments)
	if err != nil {
		t.Fatalf("ParseBytes: %v", err)
	}

	body := f.Docs[0].Body.(*ast.MappingNode)

	var layers []string
	for _, mv := range body.Values {
		if mv.Key.(*ast.StringNode).Value != probeKeyLayers {
			continue
		}
		seq, ok := mv.Value.(*ast.SequenceNode)
		if !ok {
			t.Fatalf("layers value is %T, want *ast.SequenceNode", mv.Value)
		}
		for _, entry := range seq.Values {
			s, ok := entry.(*ast.StringNode)
			if !ok {
				t.Logf("layers entry is %T (not *ast.StringNode)", entry)
				continue
			}
			layers = append(layers, s.Value)
		}
		break
	}

	want := []string{layerModel, layerCore, layerAdapter}
	if len(layers) != len(want) {
		t.Fatalf("layers = %v, want %v", layers, want)
	}
	for i, v := range layers {
		if v != want[i] {
			t.Errorf("layers[%d] = %q, want %q", i, v, want[i])
		}
	}
	t.Logf("CONFIRMED: layers sequence values = %v", layers)
}

// TestProbe_PathsBlock_LineRange verifies that the patcher can locate the
// start and end lines of a module's paths: block by reading the key token
// position of "paths" and its sequence entries.
func TestProbe_PathsBlock_LineRange(t *testing.T) {
	src := []byte(sampleArchfitYAML)
	f, err := parser.ParseBytes(src, parser.ParseComments)
	if err != nil {
		t.Fatalf("ParseBytes: %v", err)
	}

	body := f.Docs[0].Body.(*ast.MappingNode)

	var classifyMV *ast.MappingValueNode
	for _, mv := range body.Values {
		if mv.Key.(*ast.StringNode).Value != probeKeyModules {
			continue
		}
		for _, modMV := range mv.Value.(*ast.MappingNode).Values {
			if modMV.Key.(*ast.StringNode).Value == testClassify {
				classifyMV = modMV
				break
			}
		}
		break
	}
	if classifyMV == nil {
		t.Fatal(testClassify + " module not found")
	}

	classifyBody, ok := classifyMV.Value.(*ast.MappingNode)
	if !ok {
		t.Fatalf("classify value is %T", classifyMV.Value)
	}

	var pathsMV *ast.MappingValueNode
	for _, mv := range classifyBody.Values {
		if mv.Key.(*ast.StringNode).Value == probeKeyPaths {
			pathsMV = mv
			break
		}
	}
	if pathsMV == nil {
		t.Fatal(probeKeyPaths + " key not found in classify")
	}

	pathsKeyLine := pathsMV.Key.GetToken().Position.Line
	t.Logf("classify.paths key at line %d", pathsKeyLine)

	// The sequence entries have their own token positions.
	seq := pathsMV.Value.(*ast.SequenceNode)
	if len(seq.Values) == 0 {
		t.Fatal("paths sequence is empty")
	}
	for i, entry := range seq.Values {
		pos := entry.GetToken().Position
		t.Logf("  paths[%d] at line %d col %d: %s", i, pos.Line, pos.Column, entry.(*ast.StringNode).Value)
	}

	lines := strings.Split(string(src), "\n")
	if pathsKeyLine-1 >= len(lines) {
		t.Fatalf("pathsKeyLine %d out of range", pathsKeyLine)
	}
	if !strings.Contains(lines[pathsKeyLine-1], probeKeyPaths+":") {
		t.Errorf("line %d = %q, expected %q", pathsKeyLine, lines[pathsKeyLine-1], probeKeyPaths+":")
	}
	t.Logf("CONFIRMED: paths: key correctly located at line %d", pathsKeyLine)
}

// ---------------------------------------------------------------------------
// Probe 6: Module line range — key start to next sibling start
// ---------------------------------------------------------------------------

// TestProbe_ModuleLineRange_AdjacentSiblings verifies the core range-finding
// strategy: a module's line range runs from its key token line (inclusive)
// to the next sibling's key token line (exclusive). This is how the patcher
// locates the byte slice to replace or comment.
func TestProbe_ModuleLineRange_AdjacentSiblings(t *testing.T) {
	src := []byte(sampleArchfitYAML)
	f, err := parser.ParseBytes(src, parser.ParseComments)
	if err != nil {
		t.Fatalf("ParseBytes: %v", err)
	}

	body := f.Docs[0].Body.(*ast.MappingNode)

	var modulesMap *ast.MappingNode
	for _, mv := range body.Values {
		if mv.Key.(*ast.StringNode).Value == probeKeyModules {
			modulesMap = mv.Value.(*ast.MappingNode)
			break
		}
	}
	if modulesMap == nil {
		t.Fatal(probeKeyModules + " not found")
	}

	type modRange struct {
		name      string
		startLine int // key token line (1-based)
	}
	ranges := make([]modRange, 0, len(modulesMap.Values))
	for _, mv := range modulesMap.Values {
		ranges = append(ranges, modRange{
			name:      mv.Key.(*ast.StringNode).Value,
			startLine: mv.Key.GetToken().Position.Line,
		})
	}

	if len(ranges) < 2 {
		t.Fatalf("expected ≥2 modules, got %d", len(ranges))
	}

	// classify ends at (extract.startLine - 1).
	classify := ranges[0]
	extract := ranges[1]

	t.Logf("classify starts at line %d, extract at line %d", classify.startLine, extract.startLine)

	lines := strings.Split(string(src), "\n")
	if classify.startLine-1 >= len(lines) || extract.startLine-1 >= len(lines) {
		t.Fatal("line range out of bounds")
	}
	t.Logf("classify range: lines[%d..%d)", classify.startLine-1, extract.startLine-1)
	for i := classify.startLine - 1; i < extract.startLine-1; i++ {
		t.Logf("  [%d] %s", i+1, lines[i])
	}

	// Sanity: the range must include "classify:" and its body, but not "extract:".
	rangeText := strings.Join(lines[classify.startLine-1:extract.startLine-1], "\n")
	if !strings.Contains(rangeText, testClassify+":") {
		t.Errorf("range does not contain %q:\n%s", testClassify+":", rangeText)
	}
	if strings.Contains(rangeText, "extract:") {
		t.Errorf("range unexpectedly contains 'extract:':\n%s", rangeText)
	}
	t.Log("CONFIRMED: sibling-key line range correctly isolates a module stanza")
}

// keysOf returns the keys of a bool map for logging.
func keysOf(m map[string]bool) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	return ks
}
