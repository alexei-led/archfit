// mustApply applies edits and fatals on error.
func mustApply(t *testing.T, src string, edits ...Edit) string {
	t.Helper()
	out, err := ApplyEdits([]byte(src), edits)
	if err != nil {
		t.Fatalf("ApplyEdits: %v", err)
	}
	return string(out)
}

// mustRoundTrip writes yaml to a temp file and calls config.Load; fatals on error.
func mustRoundTrip(t *testing.T, yamlContent string) config.Config {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, ".archfit.yaml")
	if err := os.WriteFile(path, []byte(yamlContent), 0o600); err != nil {
		t.Fatalf("write temp: %v", err)
	}
	cfg, err := config.Load(context.Background(), path)
	if err != nil {
		t.Fatalf("config.Load round-trip failed: %v\n---yaml---\n%s", err, yamlContent)
	}
	return cfg
}

// assertContains fails if want is not in got.
func assertContains(t *testing.T, got, want string) {
	t.Helper()
	if !strings.Contains(got, want) {
		t.Errorf("output missing %q\n--- got ---\n%s", want, got)
	}
}

// assertNotContains fails if unwanted is in got.
func assertNotContains(t *testing.T, got, unwanted string) {
	t.Helper()
	if strings.Contains(got, unwanted) {
		t.Errorf("output must not contain %q\n--- got ---\n%s", unwanted, got)
	}
}

