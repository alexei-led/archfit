// ---------------------------------------------------------------------------
// Test: SetModuleFields coalesces multiple absent fields into one block
// ---------------------------------------------------------------------------

func TestApplyEdits_SetModuleFields_CoalesceMultiple(t *testing.T) {
	// classify has layer: core but no subdomain or volatility.
	ed := SetModuleFieldsEdit{
		Module: testClassify,
		Fields: map[ModuleField]string{
			FieldSubdomain:  layerCore,
			FieldVolatility: "low",
			FieldLayer:      layerCore, // already present — should be skipped
		},
	}
	out := mustApply(t, fullFixture, ed)

	assertContains(t, out, "subdomain: core")
	assertContains(t, out, "volatility: low")

	// Canonical order: subdomain before volatility.
	subIdx := strings.Index(out, "subdomain:")
	volIdx := strings.Index(out, "volatility:")
	if subIdx >= volIdx {
		t.Errorf("subdomain: (%d) should appear before volatility: (%d)", subIdx, volIdx)
	}

	// layer: core already present — should not be duplicated.
	if strings.Count(out, "layer: core") != 1 {
		t.Errorf("layer: core should appear exactly once, got %d", strings.Count(out, "layer: core"))
	}

	// Original content preserved.
	assertContains(t, out, "head comment for classify")
	assertContains(t, out, "no-forbidden-deps")

	mustRoundTrip(t, out)
}

