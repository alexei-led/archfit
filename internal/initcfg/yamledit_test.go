// ---------------------------------------------------------------------------
// Test: sanitizeComment injection guard (via CommentModule note)
// ---------------------------------------------------------------------------

func TestApplyEdits_CommentModule_SanitizesNote(t *testing.T) {
	// A note containing a newline — must not escape into live YAML.
	ed := CommentModuleEdit{
		Module: testClassify,
		Note:   "gone\nvolatility: high",
	}
	out := mustApply(t, fullFixture, ed)

	// The sanitized note must not produce a live volatility: key.
	// After sanitization, \n → ' ', so the note becomes "gone volatility: high"
	// which is inside a comment line starting with #.
	lines := strings.Split(out, "\n")
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "volatility:") {
			t.Errorf("injection: found live volatility: line not inside a comment: %q", line)
		}
	}

	// marker line exists.
	assertContains(t, out, `# archfit: removed module "classify"`)

	mustRoundTrip(t, out)
}

